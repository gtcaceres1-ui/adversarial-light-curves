"""Package the bounded adversarial light curves for public release.

For every test star of a survey, merges the clean light curve with its
adversarial counterpart (generated by ``build_adversarials_*``) into one CSV
with columns ``time, mag, mag_adv, err``, checks the photometric bound
|mag_adv - mag| <= k * err on every observation, and writes a catalog with
the class, the surrogate-CNN predictions and per-star perturbation statistics.
Each survey is then archived as a tar.gz ready for a Zenodo deposit.

Usage (from the project root, with the survey data under Data/ and the
attack outputs under runs/):

    python scripts/package_adversarial_dataset.py --out zenodo_deposit
    python scripts/package_adversarial_dataset.py --surveys ogle --out zenodo_deposit
"""
from __future__ import annotations

import argparse
import json
import tarfile
from pathlib import Path

import numpy as np
import pandas as pd

from src.data.survey_loader import build_catalog, load_lightcurve

REPO = Path(__file__).resolve().parents[1]

RUN_DIRS = {
    "ogle": "runs/adversarial_dataset",
    "gaia": "runs/gaia_adversarial_dataset",
    "wise": "runs/wise_adversarial_dataset",
}
SURVEY_NAMES = {
    "ogle": "OGLE-III",
    "gaia": "Gaia DR2",
    "wise": "WISE (W1)",
}
CLASS_NAMES = {
    "rrlyr": "RR Lyrae",
    "cep": "Cepheid",
    "lpv": "long-period variable",
    "ecl": "eclipsing binary",
    "dsct": "delta Scuti / SX Phe",
}


def package_survey(survey: str, out_root: Path, tol: float = 1e-9) -> dict:
    run_dir = REPO / RUN_DIRS[survey]
    summary = pd.read_csv(run_dir / "test_attack_summary.csv")
    meta = json.loads((run_dir / "summary.json").read_text())
    k = float(meta["k_mag"])

    if survey == "ogle":
        # The OGLE-III set keeps eclipsing binaries, which the multi-survey
        # loader drops, so read the catalog directly.
        catalog = pd.read_csv(REPO / "Data/OGLE-III/OGLE_dataset.dat")
        catalog.columns = [c.strip() for c in catalog.columns]
        catalog["ID"] = catalog["ID"].astype(str).str.strip()
        catalog["lc_file"] = catalog["ID"].apply(lambda x: REPO / "Data/OGLE-III/LCs" / f"{x}.dat")
        catalog = catalog.set_index("ID")
    else:
        catalog = build_catalog(survey).set_index("ID")
    dest = out_root / survey
    lc_dir = dest / "lightcurves"
    lc_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    worst = 0.0
    for i, rec in enumerate(summary.itertuples(index=False)):
        sid = str(rec.id).strip()
        cat_row = catalog.loc[sid]
        clean = load_lightcurve(cat_row["lc_file"], survey)
        adv = pd.read_csv(run_dir / "adversarial_lcs" / f"{sid}_adv.dat", sep=r"\s+")
        merged = clean.merge(adv, on="time", how="left", suffixes=("", "_adv"))
        if merged["magnitude_adv"].isna().any() or len(merged) != len(adv):
            raise RuntimeError(f"{survey}/{sid}: clean and adversarial epochs do not align")
        if not np.allclose(merged["error"], merged["error_adv"]):
            raise RuntimeError(f"{survey}/{sid}: reported errors differ between files")

        mag = merged["magnitude"].to_numpy()
        err = merged["error"].to_numpy()
        budget = k * err
        # Round to 1e-6 mag, then clip so the hard bound survives the rounding.
        mag_adv = np.round(merged["magnitude_adv"].to_numpy(), 6)
        mag_adv = np.clip(mag_adv, mag - budget, mag + budget)
        shift = np.abs(mag_adv - mag)
        ratio = np.where(budget > 0, shift / np.maximum(budget, 1e-12), 0.0)
        if ratio.max() > 1.0 + tol:
            raise RuntimeError(f"{survey}/{sid}: bound violated ({ratio.max():.6f})")
        worst = max(worst, float(ratio.max()))

        out = pd.DataFrame({
            "time": merged["time"].to_numpy(),
            "mag": mag,
            "mag_adv": mag_adv,
            "err": err,
        })
        out.to_csv(lc_dir / f"{sid}.csv", index=False, float_format="%.6f")

        perturbed = shift > 1e-7
        rows.append({
            "id": sid,
            "class": rec.true_label,
            "class_catalog": cat_row["Class"],
            "n_obs": len(out),
            "n_perturbed": int(perturbed.sum()),
            "median_shift_over_budget": float(np.median(ratio[perturbed])) if perturbed.any() else 0.0,
            "max_shift_over_budget": float(ratio.max()),
            "cnn_pred_clean": rec.pred_clean,
            "cnn_pred_adv": rec.pred_adv,
            "flipped": bool(rec.pred_clean != rec.pred_adv),
        })
        if (i + 1) % 2000 == 0:
            print(f"  {survey}: {i + 1}/{len(summary)}", flush=True)

    cat_out = pd.DataFrame(rows)
    cat_out.to_csv(dest / "catalog.csv", index=False, float_format="%.4f")

    stats = {
        "survey": survey,
        "n_stars": int(len(cat_out)),
        "n_flipped": int(cat_out["flipped"].sum()),
        "class_counts": cat_out["class"].value_counts().to_dict(),
        "k": k,
        "pgd_steps": meta.get("pgd_steps"),
        "pgd_restarts": meta.get("pgd_restarts"),
        "pgd_step_frac": meta.get("pgd_step_frac"),
        "smooth_lambda": meta.get("smooth_lambda"),
        "cnn_acc_clean": meta.get("cnn_acc_clean"),
        "cnn_acc_adv": meta.get("cnn_acc_adv"),
        "max_shift_over_budget": worst,
        "total_observations": int(cat_out["n_obs"].sum()),
        "total_perturbed": int(cat_out["n_perturbed"].sum()),
    }
    (dest / "attack_summary.json").write_text(json.dumps(stats, indent=2))
    return stats


def write_readme(out_root: Path, stats: list[dict]) -> None:
    lines = [
        "# Adversarial light curves within the photometric error budget",
        "",
        "Adversarial versions of the test-set light curves used in",
        "",
        "> G. Cáceres, K. Pichara, M. Catelan, F. Pérez-Galarce,",
        "> *Adversarial robustness of variable-star classifiers within the photometric error budget*,",
        "> submitted to Astronomy & Astrophysics (2026).",
        "",
        "Every adversarial magnitude stays inside the reported photometric error",
        "bar of the corresponding observation,",
        "",
        "    |mag_adv - mag| <= k * err,   with k = 0.5,",
        "",
        "and observation times and reported errors are untouched. The perturbations",
        "were optimized with projected gradient descent against a two-tower",
        "convolutional classifier trained on the (Delta t, Delta m) representation",
        "of the light curves, so they transfer to other classifiers trained on the",
        "same task. They are meant as a stress test: a classifier whose prediction",
        "changes between `mag` and `mag_adv` is sensitive to displacements that are",
        "statistically consistent with the measurement itself.",
        "",
        "## Contents",
        "",
        "One folder per survey. Inside each:",
        "",
        "* `lightcurves/<ID>.csv`: one file per star with columns",
        "  `time, mag, mag_adv, err`. `mag` is the public clean magnitude, `mag_adv`",
        "  the adversarial one (rounded to 1e-6 mag), `err` the reported error.",
        "  The attack optimized the displacement on a uniform subsample of up to",
        "  500 epochs per star; for longer light curves the displacement was",
        "  linearly interpolated in time to the remaining epochs and clipped to the",
        "  bound, so every epoch satisfies |mag_adv - mag| <= k * err.",
        "* `catalog.csv`: `id, class, class_catalog, n_obs, n_perturbed,`",
        "  `median_shift_over_budget, max_shift_over_budget, cnn_pred_clean,`",
        "  `cnn_pred_adv, flipped`. `class` is the four-class label used in the",
        "  paper, `class_catalog` the original survey class, and the `cnn_*` columns",
        "  the predictions of the surrogate classifier on the clean and adversarial",
        "  curve.",
        "* `attack_summary.json`: attack hyperparameters and aggregate statistics.",
        "",
        "## Surveys",
        "",
        "| survey | stars | flipped by the surrogate CNN | classes |",
        "|--------|------:|-----------------------------:|---------|",
    ]
    for s in stats:
        classes = ", ".join(f"{CLASS_NAMES.get(c, c)} ({n})" for c, n in sorted(s["class_counts"].items()))
        lines.append(f"| {SURVEY_NAMES[s['survey']]} | {s['n_stars']} | {s['n_flipped']} | {classes} |")
    s0 = stats[0]
    lines += [
        "",
        "## Attack protocol",
        "",
        f"Budget k = {s0['k']}; PGD with {s0['pgd_steps']} iterations, "
        f"{s0['pgd_restarts']} random restarts, step {s0['pgd_step_frac']} of the per-point budget, "
        f"and a smoothness penalty of {s0['smooth_lambda']} on the second difference of the",
        "perturbation. The stars are the 20% stratified test fold (seed 42) of a",
        "class-balanced subsample of each catalog; the surrogate CNN never saw them",
        "during training. The code that generated and validated these files is at",
        "https://github.com/gtcaceres1-ui/adversarial-light-curves.",
        "",
        "## Source data and credits",
        "",
        "The clean light curves are public data of the OGLE-III survey (Udalski et",
        "al. 2008, Acta Astron. 58, 69), *Gaia* DR2 (Gaia Collaboration 2018, A&A",
        "616, A1) and WISE (Wright et al. 2010, AJ 140, 1868), as compiled by Becker",
        "et al. (2020). Please credit those surveys when using the clean columns, and",
        "cite the paper above when using the adversarial ones.",
        "",
        "## License",
        "",
        "Creative Commons Attribution 4.0 (CC BY 4.0).",
        "",
    ]
    (out_root / "README.md").write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--surveys", default="ogle,gaia,wise")
    parser.add_argument("--out", default="zenodo_deposit")
    parser.add_argument("--no-tar", action="store_true")
    args = parser.parse_args()

    out_root = REPO / args.out
    out_root.mkdir(parents=True, exist_ok=True)
    stats = []
    for survey in args.surveys.split(","):
        print(f"== {survey}", flush=True)
        stats.append(package_survey(survey, out_root))
        print(json.dumps(stats[-1], indent=2), flush=True)
        if not args.no_tar:
            tar_path = out_root / f"adversarial_lightcurves_{survey}_k{stats[-1]['k']}.tar.gz"
            with tarfile.open(tar_path, "w:gz") as tar:
                tar.add(out_root / survey, arcname=survey)
            print(f"  wrote {tar_path} ({tar_path.stat().st_size / 1e6:.1f} MB)", flush=True)
    write_readme(out_root, stats)


if __name__ == "__main__":
    main()
